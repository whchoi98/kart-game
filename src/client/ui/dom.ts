/** Tiny DOM helpers (no framework). Text always goes through textContent. */

export type Child = Node | string | number | null | undefined | false;

export function h<K extends keyof HTMLElementTagNameMap>(
  tag: K, cls?: string | null, ...children: Child[]
): HTMLElementTagNameMap[K] {
  const el = document.createElement(tag);
  if (cls) el.className = cls;
  append(el, ...children);
  return el;
}

export function append(parent: Element, ...children: Child[]): void {
  for (const c of children) {
    if (c === null || c === undefined || c === false) continue;
    parent.append(typeof c === 'string' || typeof c === 'number' ? document.createTextNode(String(c)) : c);
  }
}

/** Wrap trusted, static SVG markup (generated by our own art modules) in a span. */
export function svg(markup: string, cls = 'ico'): HTMLSpanElement {
  const s = document.createElement('span');
  s.className = cls;
  s.setAttribute('aria-hidden', 'true');
  s.innerHTML = markup;
  return s;
}

export function clear(el: Element): void {
  while (el.firstChild) el.firstChild.remove();
}

export function setText(el: Element, text: string): void {
  if (el.textContent !== text) el.textContent = text;
}

let reducedMotionQuery: MediaQueryList | null = null;
export function prefersReducedMotion(): boolean {
  try {
    reducedMotionQuery ??= window.matchMedia('(prefers-reduced-motion: reduce)');
    return reducedMotionQuery.matches;
  } catch {
    return false;
  }
}

/** Web Animations API wrapper that respects prefers-reduced-motion. */
export function animate(
  el: Element, keyframes: Keyframe[] | PropertyIndexedKeyframes, opts: KeyframeAnimationOptions,
): Animation | null {
  if (prefersReducedMotion() || typeof el.animate !== 'function') return null;
  try {
    return el.animate(keyframes, opts);
  } catch {
    return null;
  }
}

export function wait(ms: number): Promise<void> {
  return new Promise(resolve => setTimeout(resolve, ms));
}

/** Count a number up over `ms` using rAF (instant with reduced motion). */
export function countUp(el: Element, from: number, to: number, ms: number, fmt: (v: number) => string = v => String(Math.round(v))): void {
  if (prefersReducedMotion() || ms <= 0 || from === to) {
    el.textContent = fmt(to);
    return;
  }
  const start = performance.now();
  const step = (now: number) => {
    const t = Math.min(1, (now - start) / ms);
    const e = 1 - Math.pow(1 - t, 3);
    el.textContent = fmt(from + (to - from) * e);
    if (t < 1) requestAnimationFrame(step);
  };
  requestAnimationFrame(step);
}
